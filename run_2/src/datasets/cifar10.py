"""CIFAR-10 dataset for federated learning experiments.

CIFAR-10 is a standard benchmark for image classification consisting of
60 000 32x32 colour images across 10 classes (airplane, automobile, bird,
cat, deer, dog, frog, horse, ship, truck).  Unlike MNIST, images are NOT
flattened — they are kept as 4-D tensors with shape (N, 32, 32, 3) so
convolutional architectures can exploit spatial structure.

The 50 000 training images are partitioned across nodes; the 10 000 test
images are shared globally (duplicated in every node's .npz file).
"""

from __future__ import annotations
from pathlib import Path
import numpy as np
from .base import FederationDataset
from .partitioner import create_partitioner


class CIFAR10Dataset(FederationDataset):
    """CIFAR-10 dataset for federated learning.

    Data is kept as (N, 32, 32, 3) float32 images normalised to [0, 1].
    Labels are int64 class indices in {0, ..., 9}.
    """

    def __init__(self):
        self.x_train = None
        self.y_train = None
        self.x_val = None
        self.y_val = None
        self.x_test = None
        self.y_test = None

    @classmethod
    def prepare_partitions(cls, total_nodes, output_dir, partition_strategy="iid", seed=42, **kwargs):
        """Download CIFAR-10, partition, save .npz per node."""
        import tensorflow as tf
        output_path = Path(output_dir)
        output_path.mkdir(parents=True, exist_ok=True)

        (x_train_full, y_train_full), (x_test, y_test) = tf.keras.datasets.cifar10.load_data()

        # Normalize to [0, 1]; keep spatial dimensions (N, 32, 32, 3)
        x_train_full = x_train_full.astype(np.float32) / 255.0
        y_train_full = y_train_full.astype(np.int64).ravel()
        x_test = x_test.astype(np.float32) / 255.0
        y_test = y_test.astype(np.int64).ravel()

        # Partition training data.  workers_only (baseline fix,
        # writeup/16 §5.3): partition over the num_nodes-1 workers so no
        # shard is stranded on the never-training aggregator; node-0 gets
        # a small COPIED sliver purely for file-schema compliance.
        workers_only = bool(kwargs.pop("workers_only", False))
        partitioner = create_partitioner(partition_strategy, **kwargs)
        if workers_only and total_nodes > 1:
            partitions = partitioner.partition(
                x_train_full, y_train_full, total_nodes - 1, seed
            )
            sliver_rng = np.random.RandomState(seed)
            sliver_idx = sliver_rng.choice(
                len(x_train_full),
                size=min(256, len(x_train_full)),
                replace=False,
            )
            partitions = [
                (x_train_full[sliver_idx], y_train_full[sliver_idx])
            ] + list(partitions)
        else:
            partitions = partitioner.partition(
                x_train_full, y_train_full, total_nodes, seed
            )

        paths = []
        for node_id, (x_node, y_node) in enumerate(partitions):
            # 90/10 train/val split per node
            rng = np.random.RandomState(seed + node_id)
            n = len(x_node)
            indices = rng.permutation(n)
            val_size = max(1, n // 10)
            val_idx = indices[:val_size]
            train_idx = indices[val_size:]

            # Use the same hyphenated format as Docker service names (node-0, node-1, ...)
            path = output_path / f"node-{node_id}.npz"
            np.savez(
                path,
                x_train=x_node[train_idx],
                y_train=y_node[train_idx],
                x_val=x_node[val_idx],
                y_val=y_node[val_idx],
                x_test=x_test,    # shared global test set
                y_test=y_test,
            )
            paths.append(path)
        return paths

    def load_from_file(self, path):
        """Load a pre-partitioned .npz dataset file.

        Validates that all expected array keys are present before loading.
        If any are missing — e.g. because the file is corrupted or was
        generated by an older version of the partitioner — a ValueError
        is raised with a descriptive message so the user knows to
        re-run the launcher to regenerate partitions.
        """
        data = np.load(path)
        expected_keys = {"x_train", "y_train", "x_val", "y_val", "x_test", "y_test"}
        missing = expected_keys - set(data.keys())
        if missing:
            raise ValueError(
                f"Corrupted or incomplete dataset file {path}: "
                f"missing keys {sorted(missing)}. "
                f"Available keys: {sorted(data.keys())}. "
                f"Re-run the launcher to regenerate partitions."
            )
        self.x_train = data["x_train"]
        self.y_train = data["y_train"]
        self.x_val = data["x_val"]
        self.y_val = data["y_val"]
        self.x_test = data["x_test"]
        self.y_test = data["y_test"]

    def get_input_shape(self):
        return (32, 32, 3)

    def get_num_classes(self):
        return 10

    def get_name(self):
        return "cifar10"

    def get_train_data(self):
        return self.x_train, self.y_train

    def get_val_data(self):
        return self.x_val, self.y_val

    def get_test_data(self):
        return self.x_test, self.y_test
